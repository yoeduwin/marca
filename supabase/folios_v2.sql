create or replace function private.actualizar_operador(
  p_user_id uuid,
  p_rol text,
  p_activo boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actual public.operadores%rowtype;
  v_admins integer;
begin
  if (select auth.uid()) is null or not (select private.es_admin()) then
    raise exception 'Solo un administrador puede gestionar operadores' using errcode = '42501';
  end if;
  if p_rol not in ('operador', 'administrador') then
    raise exception 'Rol no válido' using errcode = '22023';
  end if;

  select * into v_actual
  from public.operadores
  where user_id = p_user_id
  for update;

  if v_actual.user_id is null then
    raise exception 'Operador no encontrado' using errcode = 'P0002';
  end if;

  if v_actual.rol = 'administrador'
     and v_actual.activo
     and (p_rol <> 'administrador' or not p_activo) then
    select count(*) into v_admins
    from public.operadores
    where rol = 'administrador'
      and activo
      and user_id <> p_user_id;
    if v_admins = 0 then
      raise exception 'Debe permanecer al menos un administrador activo' using errcode = '23514';
    end if;
  end if;

  update public.operadores
  set rol = p_rol,
      activo = p_activo,
      updated_at = now()
  where user_id = p_user_id;

  insert into public.folio_eventos (
    folio, accion, detalle, actor_id
  ) values (
    null, 'operador_actualizado',
    jsonb_build_object('user_id', p_user_id, 'rol', p_rol, 'activo', p_activo),
    (select auth.uid())
  );

  return jsonb_build_object(
    'user_id', p_user_id,
    'rol', p_rol,
    'activo', p_activo
  );
end;
$$;

