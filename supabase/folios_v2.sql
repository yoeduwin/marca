-- Folios v2: revisiones identificables, roles y auditoría
-- Ejecutar en el proyecto Supabase antes de publicar el frontend de esta rama.
-- Conserva todos los registros existentes y corrige folios con más de una versión activa.

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

alter table public.informes
  add column if not exists public_id uuid default gen_random_uuid(),
  add column if not exists revision integer,
  add column if not exists operador_id uuid references auth.users(id),
  add column if not exists reemplaza_id uuid references public.informes(id),
  add column if not exists motivo_cambio text,
  add column if not exists updated_at timestamptz default now();

update public.informes
set public_id = gen_random_uuid()
where public_id is null;

with numbered as (
  select id,
         row_number() over (
           partition by upper(btrim(folio))
           order by created_at, id
         ) - 1 as revision_calculada,
         lag(id) over (
           partition by upper(btrim(folio))
           order by created_at, id
         ) as anterior_id
  from public.informes
)
update public.informes i
set revision = n.revision_calculada,
    reemplaza_id = coalesce(i.reemplaza_id, n.anterior_id)
from numbered n
where n.id = i.id
  and (i.revision is null or i.reemplaza_id is null);

-- Si el esquema anterior dejó varias filas activas, conserva como vigente la más reciente.
with activas as (
  select id,
         row_number() over (
           partition by upper(btrim(folio))
           order by created_at desc, id desc
         ) as posicion
  from public.informes
  where estado = 'activo'
)
update public.informes i
set estado = 'reemplazado',
    motivo_cambio = coalesce(i.motivo_cambio, 'Regularización automática: existían varias versiones activas'),
    updated_at = now()
from activas a
where a.id = i.id
  and a.posicion > 1;

alter table public.informes
  alter column public_id set not null,
  alter column revision set not null,
  alter column revision set default 0,
  alter column updated_at set not null;

create unique index if not exists informes_public_id_uq
  on public.informes(public_id);
create unique index if not exists informes_folio_revision_uq
  on public.informes(upper(btrim(folio)), revision);
create unique index if not exists informes_un_activo_por_folio_uq
  on public.informes(upper(btrim(folio)))
  where estado = 'activo';
create index if not exists informes_estado_fecha_idx
  on public.informes(estado, created_at desc);
create index if not exists informes_operador_idx
  on public.informes(operador_id);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'informes_estado_valido'
      and conrelid = 'public.informes'::regclass
  ) then
    alter table public.informes
      add constraint informes_estado_valido
      check (estado in ('activo', 'reemplazado', 'anulado')) not valid;
    alter table public.informes validate constraint informes_estado_valido;
  end if;
end $$;

create table if not exists public.operadores (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  nombre text,
  rol text not null default 'operador'
    check (rol in ('operador', 'administrador')),
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.operadores enable row level security;

-- El usuario ya existente queda como administrador inicial.
insert into public.operadores (user_id, email, nombre, rol, activo)
select u.id,
       u.email,
       coalesce(nullif(u.raw_user_meta_data ->> 'nombre', ''), split_part(u.email, '@', 1)),
       case
         when row_number() over (order by u.created_at, u.id) = 1
           then 'administrador'
         else 'operador'
       end,
       true
from auth.users u
on conflict (user_id) do nothing;

create table if not exists public.folio_eventos (
  id bigint generated by default as identity primary key,
  informe_id uuid references public.informes(id),
  folio text,
  accion text not null,
  detalle jsonb not null default '{}'::jsonb,
  actor_id uuid references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.folio_eventos enable row level security;
create index if not exists folio_eventos_folio_fecha_idx
  on public.folio_eventos(upper(btrim(folio)), created_at desc);
create index if not exists folio_eventos_actor_idx
  on public.folio_eventos(actor_id);

create or replace function private.es_operador()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.operadores o
    where o.user_id = (select auth.uid())
      and o.activo
      and o.rol in ('operador', 'administrador')
  );
$$;

create or replace function private.es_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.operadores o
    where o.user_id = (select auth.uid())
      and o.activo
      and o.rol = 'administrador'
  );
$$;

revoke execute on function private.es_operador() from public, anon;
revoke execute on function private.es_admin() from public, anon;
grant execute on function private.es_operador() to authenticated;
grant execute on function private.es_admin() to authenticated;

