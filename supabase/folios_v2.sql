create or replace function private.anular_folio(
  p_folio text,
  p_motivo text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_folio text := upper(btrim(coalesce(p_folio, '')));
  v_motivo text := btrim(coalesce(p_motivo, ''));
  v_informe public.informes%rowtype;
begin
  if (select auth.uid()) is null or not (select private.es_admin()) then
    raise exception 'Solo un administrador puede anular folios' using errcode = '42501';
  end if;
  if length(v_motivo) < 5 then
    raise exception 'Escribe un motivo de anulación' using errcode = '22023';
  end if;

  select *
  into v_informe
  from public.informes
  where upper(btrim(folio)) = v_folio
    and estado = 'activo'
  order by created_at desc, id desc
  limit 1
  for update;

  if v_informe.id is null then
    raise exception 'No existe una versión vigente para ese folio' using errcode = 'P0002';
  end if;

  update public.informes
  set estado = 'anulado',
      motivo_cambio = v_motivo,
      updated_at = now()
  where id = v_informe.id;

  insert into public.folio_eventos (
    informe_id, folio, accion, detalle, actor_id
  ) values (
    v_informe.id, v_folio, 'anulacion',
    jsonb_build_object('revision', v_informe.revision, 'motivo', v_motivo),
    (select auth.uid())
  );

  return jsonb_build_object(
    'id', v_informe.id,
    'folio', v_folio,
    'revision', v_informe.revision,
    'estado', 'anulado'
  );
end;
$$;

create or replace function public.anular_folio(
