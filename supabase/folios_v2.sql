create or replace function private.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.operadores (user_id, email, nombre, rol, activo)
  values (
    new.id,
    new.email,
    coalesce(nullif(new.raw_user_meta_data ->> 'nombre', ''), split_part(new.email, '@', 1)),
    'operador',
    true
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists crear_perfil_operador on auth.users;
create trigger crear_perfil_operador
after insert on auth.users
for each row execute function private.crear_perfil_usuario();

